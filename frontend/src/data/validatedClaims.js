export function matchValidatedClaim(claim, corpus = VALIDATED_CLAIMS) {
  if (!claim) return null;
  const cluster = (claim.cluster || '').toLowerCase();
  const text = (claim.text || '').toLowerCase();
  return corpus.find((row) => {
    if (row.claim_id === claim.id) return true;
    const topic = (row.topic || '').toLowerCase();
    return (topic && (cluster.includes(topic) || text.includes(topic.replace('-', ' '))))
      || (row.claim_id && text.includes(row.claim_id.toLowerCase()));
  }) || null;
}
